import React, { useEffect, useId, useMemo, useRef, useState } from 'react';
import Icon from './Icon';

export type SelectionOption = {
   label:string,
   value: string
}
type SelectFieldProps = {
   defaultLabel: string,
   options: SelectionOption[],
   selected: string[],
   label?: string,
   multiple?: boolean,
   updateField: (values: string[]) => void,
   fullWidth?: boolean,
   minWidth?: number,
   maxHeight?: number|string,
   rounded?: string,
   flags?: boolean,
   inline?: boolean,
   emptyMsg?: string
}
const SelectField = (props: SelectFieldProps) => {
   const {
      options,
      selected,
      defaultLabel = 'Select an Option',
      multiple = true,
      updateField,
      minWidth = 180,
      maxHeight = 96,
      fullWidth = false,
      rounded = 'rounded-3xl',
      inline = false,
      flags = false,
      label = '',
      emptyMsg = '' } = props;

   // maxHeight is in Tailwind spacing units (48 = 12rem, 96 = 24rem) or a CSS length string.
   // A dynamic `max-h-${n}` class is never generated by Tailwind, so the height is applied as an inline style.
   const listMaxHeight = typeof maxHeight === 'number' ? `${maxHeight / 4}rem` : maxHeight;
   const [showOptions, setShowOptions] = useState<boolean>(false);
   const [filterInput, setFilterInput] = useState<string>('');
   const containerRef = useRef<HTMLDivElement>(null);
   const controlRef = useRef<HTMLDivElement>(null);
   const controlId = useId();
   const optionListId = `${controlId}-options`;
   const labelId = `${controlId}-label`;
   const valueId = `${controlId}-value`;
   const [activeIndex, setActiveIndex] = useState(0);

   // Close the dropdown on outside click or Escape. Listeners exist only while open.
   useEffect(() => {
      if (!showOptions) {
         // A new opening starts with an unfiltered list
         setFilterInput('');
         return undefined;
      }

      const handleMouseDown = (event: MouseEvent) => {
         if (containerRef.current && !containerRef.current.contains(event.target as Node)) {
            setShowOptions(false);
         }
      };
      const handleKeyDown = (event: KeyboardEvent) => {
         if (event.key === 'Escape') {
            setShowOptions(false);
            controlRef.current?.focus();
         }
      };

      document.addEventListener('mousedown', handleMouseDown);
      document.addEventListener('keydown', handleKeyDown);
      return () => {
         document.removeEventListener('mousedown', handleMouseDown);
         document.removeEventListener('keydown', handleKeyDown);
      };
   }, [showOptions]);

   // Derived from the current options so the list never shows options that were removed or changed since typing
   const visibleOptions = useMemo(() => {
      if (options.length <= 20 || !filterInput) { return options; }
      const userVal = filterInput.toLowerCase();
      return options.filter((option) => (flags ? option.label.toLowerCase().startsWith(userVal) : option.label.toLowerCase().includes(userVal)));
   }, [options, filterInput, flags]);
   // A caller-supplied emptyMsg replaces the default "No options" row when there are no options at all.
   const showEmptyMsg = Boolean(emptyMsg) && options.length === 0;

   const selectedLabels = useMemo(() => options.reduce((acc:string[], item:SelectionOption) :string[] => selected.includes(item.value) ? [...acc, item.label] : [...acc], []), [selected, options]);

   const selectItem = (option:SelectionOption) => {
      let updatedSelect = [option.value];
      if (multiple && Array.isArray(selected)) {
         if (selected.includes(option.value)) {
            updatedSelect = selected.filter((x) => x !== option.value);
         } else {
            updatedSelect = [...selected, option.value];
         }
      }
      updateField(updatedSelect);
      if (!multiple) {
         setShowOptions(false);
         controlRef.current?.focus();
      }
   };

   const openOptions = () => {
      const selectedIndex = options.findIndex((option) => selected.includes(option.value));
      setActiveIndex(selectedIndex >= 0 ? selectedIndex : 0);
      setShowOptions(true);
   };

   const moveActive = (offset: number) => {
      if (visibleOptions.length === 0) { return; }
      setActiveIndex((current) => (current + offset + visibleOptions.length) % visibleOptions.length);
   };

   const handleControlKeyDown = (event: React.KeyboardEvent<HTMLDivElement>) => {
      if (event.key === 'Escape' && showOptions) {
         event.preventDefault();
         event.stopPropagation();
         setShowOptions(false);
         controlRef.current?.focus();
      } else if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
         event.preventDefault();
         if (!showOptions) {
            openOptions();
         } else {
            moveActive(event.key === 'ArrowDown' ? 1 : -1);
         }
      } else if (event.key === 'Home' && showOptions && visibleOptions.length > 0) {
         event.preventDefault();
         setActiveIndex(0);
      } else if (event.key === 'End' && showOptions && visibleOptions.length > 0) {
         event.preventDefault();
         setActiveIndex(visibleOptions.length - 1);
      } else if ((event.key === 'Enter' || event.key === ' ') && !showOptions) {
         event.preventDefault();
         openOptions();
      } else if ((event.key === 'Enter' || event.key === ' ') && showOptions) {
         event.preventDefault();
         if (visibleOptions[activeIndex]) { selectItem(visibleOptions[activeIndex]); }
      }
   };

   const handleSearchKeyDown = (event: React.KeyboardEvent<HTMLInputElement>) => {
      if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
         event.preventDefault();
         moveActive(event.key === 'ArrowDown' ? 1 : -1);
         controlRef.current?.focus();
      } else if (event.key === 'Escape') {
         event.preventDefault();
         event.stopPropagation();
         setShowOptions(false);
         controlRef.current?.focus();
      }
   };

   const filterOptions = (event:React.FormEvent<HTMLInputElement>) => {
      setFilterInput(event.currentTarget.value);
      setActiveIndex(0);
   };

   return (
      <div ref={containerRef} className={`select font-semibold text-gray-500 relative ${inline ? 'inline-block' : 'flex'} justify-between items-center`}>
         {label && <span id={labelId} className='mb-2 font-semibold inline-block text-sm text-gray-700 capitalize'>{label}</span>}
         <div
         ref={controlRef}
         id={controlId}
         role="combobox"
         tabIndex={0}
         aria-haspopup="listbox"
         aria-expanded={showOptions}
         aria-controls={optionListId}
         aria-labelledby={label ? `${labelId} ${valueId}` : undefined}
         aria-label={!label ? defaultLabel : undefined}
         aria-activedescendant={showOptions && visibleOptions[activeIndex] ? `${optionListId}-option-${activeIndex}` : undefined}
         onKeyDown={handleControlKeyDown}
         className={`selected flex border ${rounded} p-1.5 px-4 cursor-pointer select-none ${fullWidth ? 'w-full' : 'w-full sm:w-[210px]'}
         min-w-0 ${showOptions ? 'border-indigo-200' : ''}`}
         style={fullWidth ? undefined : { minWidth }}
         onClick={() => { if (showOptions) { setShowOptions(false); } else { openOptions(); } }}>
            <span className={'w-full inline-block truncate mr-2 capitalize'}>
               <span id={valueId}>{selected.length > 0 ? (selectedLabels.slice(0, 2).join(', ')) : defaultLabel}</span>
            </span>
            {multiple && selected.length > 2
            && <span className={`px-2 py-0 ${rounded} bg-[#eaecff] text-[0.7rem] font-bold`}>{(selected.length)}</span>}
            <span className='ml-2'><Icon type={showOptions ? 'caret-up' : 'caret-down'} size={9} /></span>
         </div>
         {showOptions && (
            <div
            className={`select_list mt-1 border absolute min-w-0 top-[30px] right-0 ${fullWidth ? 'w-full' : 'w-full sm:w-[210px]'}
            ${rounded === 'rounded-3xl' ? 'rounded-lg' : rounded} bg-white z-50 overflow-y-auto styled-scrollbar`}
            style={{ ...(fullWidth ? {} : { minWidth }), maxHeight: listMaxHeight }}>
               {options.length > 20 && (
                  <div className=''>
                     <input
                     className=' border-b-[1px] p-3 w-full focus:outline-0 focus:border-blue-100'
                     type="text"
                     aria-label={`Search ${label || defaultLabel}`}
                     placeholder='Search..'
                     onChange={filterOptions}
                     onKeyDown={handleSearchKeyDown}
                     value={filterInput}
                     />
                  </div>
               )}
               {showEmptyMsg && <p className='p-4'>{emptyMsg}</p>}
               <ul id={optionListId} role="listbox" aria-multiselectable={multiple || undefined}>
                  {visibleOptions.length === 0 && !showEmptyMsg && (
                     <li className='select-none px-3 py-2 text-gray-400 cursor-not-allowed'>
                        No options
                     </li>
                  )}
                  {visibleOptions.map((opt, index) => {
                     const itemActive = selected.includes(opt.value);
                     return (
                        <li
                        key={opt.value}
                        id={`${optionListId}-option-${index}`}
                        role="option"
                        aria-selected={itemActive}
                        className={`select-none cursor-pointer px-3 py-2 hover:bg-[#FCFCFF] capitalize text-ellipsis overflow-hidden
                        ${itemActive ? ' bg-indigo-50 text-indigo-600 hover:bg-indigo-50' : ''} ${index === activeIndex ? 'outline outline-1 outline-indigo-300' : ''}`}
                        onMouseEnter={() => setActiveIndex(index)}
                        onMouseDown={(event) => event.preventDefault()}
                        onClick={() => selectItem(opt)}
                        >
                           {multiple && (
                              <span
                                 className={`p-0 mr-2 leading-[0px] inline-block rounded-sm pt-0 px-[1px] pb-[3px] border
                                 ${itemActive ? ' bg-indigo-600 border-indigo-600 text-white' : 'text-transparent'}`} >
                                 <Icon type="check" size={10} />
                              </span>
                           )}
                           {flags && <span className={`fflag fflag-${opt.value} w-[15px] h-[10px] mr-1`} />}
                           {opt.label}
                        </li>
                     );
                  })}
               </ul>
            </div>
         )}
       </div>
   );
 };

 export default SelectField;
